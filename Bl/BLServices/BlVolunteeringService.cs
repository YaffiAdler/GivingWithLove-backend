using Bl.BLApi;
using Bl.BLModels;
using Bl.Exceptions;
using Dal.Api;
using Dal.Models;

namespace Bl.BLServices
{
    public class BlVolunteeringService : BlVolunteeringInterface
    {
        private const string EntityName = nameof(Volunteering);

        private readonly DalVolunteeringInterface dal;
        private readonly BlVolunteerInterface volunteerService;
        private readonly BlProjectInterface projectService;
        private readonly BlSubProjectInterface subProjectService;

        public BlVolunteeringService(
            DalVolunteeringInterface dal,
            BlVolunteerInterface volunteerService,
            BlProjectInterface projectService,
            BlSubProjectInterface subProjectService)
        {
            this.dal = dal;
            this.volunteerService = volunteerService;
            this.projectService = projectService;
            this.subProjectService = subProjectService;
        }

        public async Task<List<BlVolunteeringModel>> GetAllAsync(CancellationToken ct)
        {
            List<Volunteering> volunteerings = await dal.GetAllAsync(ct);
            List<BlVolunteeringModel> models = new List<BlVolunteeringModel>();
            // Sequential on purpose: the scoped DbContext does not support parallel queries.
            foreach (Volunteering volunteering in volunteerings)
            {
                models.Add(await ToModelWithNamesAsync(volunteering, ct));
            }
            return models;
        }

        public async Task<BlVolunteeringModel?> GetByIdAsync(int id, CancellationToken ct)
        {
            Volunteering? volunteering = await dal.GetByIdAsync(id, ct);
            return volunteering == null ? null : await ToModelWithNamesAsync(volunteering, ct);
        }

        public async Task<BlVolunteeringModel> CreateAsync(BlVolunteeringModel item, CancellationToken ct)
        {
            Volunteering entity = ToEntity(item);
            // The key is generated by the database; a client-supplied value must not reach the INSERT.
            entity.VolunteeringCode = 0;
            Volunteering created = await dal.CreateAsync(entity, ct);
            return ToModel(created);
        }

        public async Task UpdateAsync(BlVolunteeringModel item, CancellationToken ct)
        {
            if (!await dal.UpdateAsync(ToEntity(item), ct))
                throw new NotFoundException(EntityName, item.VolunteeringCode);
        }

        public async Task DeleteAsync(int id, CancellationToken ct)
        {
            if (!await dal.DeleteAsync(id, ct))
                throw new NotFoundException(EntityName, id);
        }

        private static Volunteering ToEntity(BlVolunteeringModel volunteering)
        {
            return new Volunteering()
            {
                VolunteeringCode = volunteering.VolunteeringCode,
                DateOfVolunteering = volunteering.DateOfVolunteering,
                MatcherCode = volunteering.MatcherCode,
                VolunteerCode = volunteering.VolunteerCode,
                PoorManCode = volunteering.PoorManCode,
                ProjectCode = volunteering.ProjectCode,
                SubProjectCode = volunteering.SubProjectCode
            };
        }

        private static BlVolunteeringModel ToModel(Volunteering volunteering)
        {
            return new BlVolunteeringModel()
            {
                VolunteeringCode = volunteering.VolunteeringCode,
                DateOfVolunteering = volunteering.DateOfVolunteering,
                MatcherCode = volunteering.MatcherCode,
                VolunteerCode = volunteering.VolunteerCode,
                PoorManCode = volunteering.PoorManCode,
                ProjectCode = volunteering.ProjectCode,
                SubProjectCode = volunteering.SubProjectCode
            };
        }

        // Per-row lookups and resolving PoorManCode as a Volunteer are known issues, fixed in BE-03.
        private async Task<BlVolunteeringModel> ToModelWithNamesAsync(Volunteering volunteering, CancellationToken ct)
        {
            BlVolunteeringModel model = ToModel(volunteering);
            if (volunteering.MatcherCode != null)
            {
                model.MatcherName = await GetVolunteerFullNameAsync(volunteering.MatcherCode ?? 0, ct);
                model.VolunteerName = await GetVolunteerFullNameAsync(volunteering.VolunteerCode ?? 0, ct);
                model.PoorManName = await GetVolunteerFullNameAsync(volunteering.PoorManCode ?? 0, ct);
            }
            if (volunteering.ProjectCode is int projectCode)
            {
                BlProjectModel project = await projectService.GetByIdAsync(projectCode, ct)
                    ?? throw new NotFoundException(nameof(Project), projectCode);
                model.ProjectName = project.ProjectName;
            }
            if (volunteering.SubProjectCode is int subProjectCode)
            {
                BlSubProjectModel subProject = await subProjectService.GetByIdAsync(subProjectCode, ct)
                    ?? throw new NotFoundException(nameof(SubProject), subProjectCode);
                model.SubProjectName = subProject.SubProjectName;
            }
            return model;
        }

        private async Task<string> GetVolunteerFullNameAsync(int volunteerCode, CancellationToken ct)
        {
            BLVolunteerModel volunteer = await volunteerService.GetByIdAsync(volunteerCode, ct)
                ?? throw new NotFoundException(nameof(Volunteer), volunteerCode);
            return volunteer.VolunteerCodeNavigation?.FirstName + " " + volunteer.VolunteerCodeNavigation?.FamilyName;
        }
    }
}
